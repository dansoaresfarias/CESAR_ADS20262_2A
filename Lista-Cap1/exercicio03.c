/* Este programa demonstra o uso de comentários em C
 * de múltiplas linhas e de uma única linha.
 *
 *              Exercicio 03
 ***************************************************/

#include <stdio.h>  /* Para printf() */
#include <stdlib.h> /* Para system() */

int main() /* Função main: ponto de entrada do programa */
{ /* início do corpo da função main */

    printf("Estudando a Linguagem C.\n"); /* imprime uma mensagem na tela */

    system("PAUSE"); /* Pausa o console no Windows */
    return 0;
} /* fim do corpo da função main */
